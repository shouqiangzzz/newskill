export const calculateSkillLevel = (xp: number, isUnlocked: boolean): SkillLevel => {
  if (!isUnlocked) return 'locked';
  if (xp >= 2601) return 'master';
  if (xp >= 1401) return 'advanced';
  if (xp >= 601) return 'intermediate';
  if (xp >= 201) return 'apprentice';
  return 'novice';
};

export const checkIsSkillUnlocked = (skill: SkillNode, allSkills: SkillNode[]): boolean => {
  if (skill.prerequisiteIds.length === 0) return true;
  return skill.prerequisiteIds.every(prereqId => {
    const parent = allSkills.find(s => s.id === prereqId);
    if (!parent) return true;
    // Parent must have at least reached 'apprentice' (or higher) to unlock dependent skill
    return parent.currentXp >= LEVEL_CONFIG.apprentice.minXp;
  });
};
